#!/usr/bin/env node
// Generates index.d.ts (the TypeScript surface of the `pledgepack` npm
// package) from `pledgepack schema` output, so the shipped config types can
// never drift from what the Rust binary actually accepts.
//
// Usage: node scripts/generate-config-types.mjs [schema.json]
//   With no argument it shells out to `bin/pledge.js schema`.

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const schemaPath = process.argv[2];
const schema = schemaPath
  ? JSON.parse(readFileSync(schemaPath, 'utf8'))
  : JSON.parse(
      execFileSync(process.execPath, [join(root, 'bin/pledge.js'), 'schema'], {
        encoding: 'utf8',
        maxBuffer: 64 * 1024 * 1024,
      })
    );

const defs = schema.$defs ?? {};

/** JSON-schema type → TS type text. */
function tsType(node, nameHint) {
  if (node == null || typeof node !== 'object') return 'unknown';
  if (node.$ref) {
    const ref = node.$ref.split('/').pop();
    return defs[ref] ? ref : 'unknown';
  }
  if (node.enum) {
    return node.enum.map((v) => JSON.stringify(v)).join(' | ');
  }
  if (node.oneOf || node.anyOf) {
    const parts = (node.oneOf ?? node.anyOf).map((n) => tsType(n, nameHint));
    return [...new Set(parts)].join(' | ') || 'unknown';
  }
  const t = node.type;
  if (Array.isArray(t)) {
    // e.g. ["string","null"] → string | null
    const nonNull = t.filter((x) => x !== 'null');
    const base =
      nonNull.length === 1
        ? tsType({ ...node, type: nonNull[0] }, nameHint)
        : nonNull.map((x) => tsType({ ...node, type: x }, nameHint)).join(' | ');
    return t.includes('null') ? `${base} | null` : base;
  }
  switch (t) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `${wrap(tsType(node.items ?? {}, nameHint))}[]`;
    case 'object': {
      if (node.properties) {
        return inlineObject(node);
      }
      if (node.additionalProperties && typeof node.additionalProperties === 'object') {
        return `Record<string, ${tsType(node.additionalProperties, nameHint)}>`;
      }
      return 'Record<string, unknown>';
    }
    default:
      return 'unknown';
  }
}

/** Parenthesize union types when used as an array element. */
function wrap(t) {
  return t.includes(' | ') ? `(${t})` : t;
}

function inlineObject(node) {
  const required = new Set(node.required ?? []);
  const lines = Object.entries(node.properties ?? {}).map(([key, sub]) => {
    const opt = required.has(key) ? '' : '?';
    return `${JSON.stringify(key)}${opt}: ${tsType(sub, key)}`;
  });
  return `{ ${lines.join('; ')} }`;
}

/** Escape text for safe inclusion inside a JSDoc block comment. */
function docSafe(text) {
  // `*/` would terminate the comment early (real descriptions contain globs
  // like `**/*.{}`); `&#47;` renders as `/` in IDE hover.
  return String(text).replace(/\*\//g, '*&#47;');
}

function doc(node, indent) {
  const parts = [];
  if (node.description) parts.push(docSafe(node.description));
  if (node.default !== undefined && typeof node.default !== 'object') {
    parts.push(`@default ${JSON.stringify(node.default)}`);
  }
  if (!parts.length) return '';
  const pad = ' '.repeat(indent);
  if (parts.length === 1 && parts[0].length + indent < 76) {
    return `${pad}/** ${parts[0]} */\n`;
  }
  return `${pad}/**\n${parts.map((p) => `${pad} * ${p}`).join('\n')}\n${pad} */\n`;
}

function emitInterface(name, node) {
  const required = new Set(node.required ?? []);
  let out = doc(node, 0) + `export interface ${name} {\n`;
  for (const [key, sub] of Object.entries(node.properties ?? {})) {
    const opt = required.has(key) ? '' : '?';
    out += doc(sub, 2);
    out += `  ${JSON.stringify(key)}${opt}: ${tsType(sub, key)};\n`;
  }
  out += '}\n';
  return out;
}

let out = `// Generated by scripts/generate-config-types.mjs from \`pledgepack schema\`.
// Do not edit by hand — run \`pnpm run gen:types\` after changing the config
// schema in crates/core/src/config.rs.

`;

for (const [name, node] of Object.entries(defs)) {
  if (node.type === 'object' && node.properties) {
    out += emitInterface(name, node) + '\n';
  } else {
    // Non-object defs (string enums, unions) become type aliases.
    out += doc(node, 0) + `export type ${name} = ${tsType(node, name)};\n\n`;
  }
}

out += emitInterface('PledgeConfig', schema);

out += `
/**
 * Identity helper so \`pledge.config.ts\` gets typed autocompletion.
 * The native binary reads the config file directly; this only shapes the
 * TypeScript/IDE experience.
 */
export declare function defineConfig(config: PledgeConfig): PledgeConfig;
`;

writeFileSync(join(root, 'index.d.ts'), out);
console.log(`wrote index.d.ts (${defsCount(defs)} $defs, ${Object.keys(schema.properties ?? {}).length} config fields)`);

function defsCount(d) {
  return Object.values(d).filter((n) => n.type === 'object').length;
}
